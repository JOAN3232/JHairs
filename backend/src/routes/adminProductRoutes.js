const router = express.Router();

// Apply administrator authentication to ALL
// routes in this file.
router.use(requireAdmin);

// ============================================
// VALID PRODUCT CATEGORIES
// ============================================

const allowedCategories = [
  "Wigs",
  "Bundles",
  "Closures",
  "Frontals",
];

// These are the only product details that
// administrators can supply through the form.
const allowedProductFields = new Set([
  "name",
  "category",
  "description",
  "image",
  "basePrice",
  "lengths",
  "colors",
  "densities",
  "laceTypes",
]);

// ============================================
// HELPER — VALIDATE TEXT
// ============================================

function validText(value, maxLength) {
  return (
    typeof value === "string" &&
    value.trim().length > 0 &&
    value.trim().length <= maxLength
  );
}

// ============================================
// HELPER — VALIDATE IMAGE URL
// ============================================

function validImage(value) {
  if (
    typeof value !== "string" ||
    value.length === 0 ||
    value.length > 2000
  ) {
    return false;
  }

  // Continue supporting existing local images
  // stored inside the React public directory.
  if (
    /^\/images\/[a-zA-Z0-9/_-]+\.(png|jpg|jpeg|webp)$/i.test(
      value
    )
  ) {
    return true;
  }

  // Accept hosted HTTPS images, including
  // images returned by Cloudinary.
  try {
    const url = new URL(value);

    return (
      url.protocol === "https:" &&
      Boolean(url.hostname)
    );
  } catch {
    return false;
  }
}

// ============================================
// HELPER — VALIDATE MONEY
// ============================================

function validMoney(value) {
  return (
    Number.isSafeInteger(value) &&
    value >= 0
  );
}

// ============================================
// HELPER — VALIDATE TEXT OPTIONS
// ============================================

function validTextOptions(options) {
  if (
    !Array.isArray(options) ||
    options.length > 30
  ) {
    return false;
  }

  const normalized = [];

  for (const option of options) {
    if (!validText(option, 60)) {
      return false;
    }

    normalized.push(
      option.trim().toLowerCase()
    );
  }

  // Prevent duplicate option names.
  return (
    new Set(normalized).size ===
    normalized.length
  );
}

// ============================================
// HELPER — VALIDATE HAIR LENGTHS
// ============================================

function validLengths(lengths) {
  if (
    !Array.isArray(lengths) ||
    lengths.length === 0 ||
    lengths.length > 30
  ) {
    return false;
  }

  if (
    !lengths.every(
      (length) =>
        Number.isSafeInteger(length) &&
        length >= 1 &&
        length <= 100
    )
  ) {
    return false;
  }

  // Hair lengths must be unique.
  return (
    new Set(lengths).size ===
    lengths.length
  );
}

// ============================================
// HELPER — VALIDATE HAIR COLOURS
// ============================================

function validColors(colors) {
  if (
    !Array.isArray(colors) ||
    colors.length === 0 ||
    colors.length > 30
  ) {
    return false;
  }

  const colorNames = [];

  for (const color of colors) {
    if (
      !color ||
      typeof color !== "object" ||
      Array.isArray(color)
    ) {
      return false;
    }

    // Validate the colour name.
    if (!validText(color.name, 60)) {
      return false;
    }

    // Require a six-digit colour swatch.
    if (
      typeof color.hex !== "string" ||
      !/^#[0-9a-fA-F]{6}$/.test(color.hex)
    ) {
      return false;
    }

    // Every colour must have an image.
    if (!validImage(color.image)) {
      return false;
    }

    // Additional colour prices cannot
    // be negative or fractional.
    if (!validMoney(color.extraPrice)) {
      return false;
    }

    colorNames.push(
      color.name.trim().toLowerCase()
    );
  }

  // Prevent duplicate colour names.
  return (
    new Set(colorNames).size ===
    colorNames.length
  );
}

// ============================================
// HELPER — VALIDATE PRODUCT INFORMATION
// ============================================

/**
 * Both product creation and editing use
 * this helper, so their validation rules
 * stay consistent.
 */
function validateProductBody(body) {
  if (
    !body ||
    typeof body !== "object" ||
    Array.isArray(body)
  ) {
    return {
      error: "Invalid product information.",
    };
  }

  // Block administrators from changing
  // protected fields such as:
  // legacyId, inventory, stock, featured,
  // isActive and _id through this endpoint.
  const unexpectedFields = Object.keys(
    body
  ).filter(
    (field) => !allowedProductFields.has(field)
  );

  if (unexpectedFields.length > 0) {
    return {
      error:
        "Unexpected product fields were provided.",
    };
  }

  const {
    name,
    category,
    description,
    image,
    basePrice,
    lengths,
    colors,
    densities = [],
    laceTypes = [],
  } = body;

  if (!validText(name, 120)) {
    return {
      error: "Enter a valid product name.",
    };
  }

  if (!allowedCategories.includes(category)) {
    return {
      error: "Select a valid product category.",
    };
  }

  if (!validText(description, 3000)) {
    return {
      error: "Enter a valid product description.",
    };
  }

  if (!validImage(image)) {
    return {
      error: "Enter a valid product image URL.",
    };
  }

  if (
    !validMoney(basePrice) ||
    basePrice === 0
  ) {
    return {
      error:
        "Starting price must be a positive whole number.",
    };
  }

  if (!validLengths(lengths)) {
    return {
      error:
        "Provide valid, unique hair lengths.",
    };
  }

  if (!validColors(colors)) {
    return {
      error:
        "Provide valid, unique hair colours with images and prices.",
    };
  }

  if (
    !validTextOptions(densities) ||
    !validTextOptions(laceTypes)
  ) {
    return {
      error:
        "Provide valid, unique density and lace options.",
    };
  }

  // Normalize values before saving.
  return {
    data: {
      name: name.trim(),
      category,
      description: description.trim(),
      image,
      basePrice,

      // Sort lengths in ascending order.
      lengths: [...lengths].sort(
        (a, b) => a - b
      ),

      colors: colors.map((color) => ({
        name: color.name.trim(),
        hex: color.hex,
        image: color.image,
        extraPrice: color.extraPrice,
      })),

      densities: densities.map(
        (item) => item.trim()
      ),

      laceTypes: laceTypes.map(
        (item) => item.trim()
      ),
    },
  };
}

// ============================================
// HELPER — FIND PRODUCT BY ID
// ============================================

/**
 * Original products use numerical legacy IDs.
 * MongoDB also has its own document IDs.
 *
 * This helper supports either format.
 */
async function findProduct(id) {
  if (/^\d+$/.test(id)) {
    const legacyId = Number(id);

    if (!Number.isSafeInteger(legacyId)) {
      return null;
    }

    return Product.findOne({ legacyId });
  }

  if (/^[0-9a-fA-F]{24}$/.test(id)) {
    return Product.findById(id);
  }

  return null;
}

// ============================================
// HELPER — GENERATE NEXT PRODUCT ID
// ============================================

async function generateProductId() {
  // Initialize the counter after the
  // four original JHAIRS products.
  await Counter.updateOne(
    { _id: "productLegacyId" },
    {
      $setOnInsert: {
        value: 4,
      },
    },
    {
      upsert: true,
    }
  );

  // Generate the next ID atomically.
  const counter =
    await Counter.findOneAndUpdate(
      { _id: "productLegacyId" },
      {
        $inc: { value: 1 },
      },
      {
        new: true,
      }
    );

  if (!counter) {
    throw new Error(
      "Unable to generate product ID."
    );
  }

  return counter.value;
}

// ============================================
// HELPER — INVENTORY COMPATIBILITY
// ============================================

/**
 * Before editing product variations, check
 * whether existing inventory records still
 * match the new product options.
 *
 * This prevents stock records from being
 * silently disconnected from their colours,
 * lengths, densities or lace types.
 */
function inventoryMatchesOptions(
  inventory,
  productData
) {
  const colors = new Set(
    productData.colors.map(
      (color) => color.name
    )
  );

  const lengths = new Set(
    productData.lengths
  );

  const densities = new Set(
    productData.densities
  );

  const laceTypes = new Set(
    productData.laceTypes
  );

  return (inventory || []).every((item) => {
    // Every existing inventory colour must
    // still exist in the edited product.
    if (!colors.has(item.color)) {
      return false;
    }

    // Every existing inventory length must
    // still be a selectable option.
    if (!lengths.has(item.length)) {
      return false;
    }

    // Check density only when this
    // inventory record uses one.
    if (
      item.density &&
      !densities.has(item.density)
    ) {
      return false;
    }

    // Check lace type only when this
    // inventory record uses one.
    if (
      item.laceType &&
      !laceTypes.has(item.laceType)
    ) {
      return false;
    }

    // Also reject stale blank dimensions
    // if the edited product now requires them.
    if (
      !item.density &&
      productData.densities.length > 0
    ) {
      return false;
    }

    if (
      !item.laceType &&
      productData.laceTypes.length > 0
    ) {
      return false;
    }

    return true;
  });
}

// ============================================
// HELPER — VALIDATE STOCK FOR PUBLISHING
// ============================================

/**
 * A product may be published only if:
 * - It has at least one inventory record.
 * - All recorded stock values are valid.
 * - Its inventory matches its current options.
 * - At least one unit is available.
 */
function canPublish(product) {
  const inventory = product.inventory || [];

  if (inventory.length === 0) {
    return false;
  }

  const stockValuesAreValid =
    inventory.every(
      (item) =>
        Number.isSafeInteger(item.stock) &&
        item.stock >= 0
    );

  if (!stockValuesAreValid) {
    return false;
  }

  if (
    !inventoryMatchesOptions(
      inventory,
      product
    )
  ) {
    return false;
  }

  const totalStock = inventory.reduce(
    (total, item) => total + item.stock,
    0
  );

  return totalStock > 0;
}

// ============================================
// HELPER — HANDLE DATABASE ERRORS
// ============================================

function handleDatabaseError(
  res,
  error,
  action
) {
  console.error(
    `JHAIRS product ${action} failed:`,
    error
  );

  if (error.code === 11000) {
    return res.status(409).json({
      success: false,
      message:
        "Product ID conflict. Please check the product ID counter.",
    });
  }

  if (error.name === "ValidationError") {
    return res.status(400).json({
      success: false,
      message: "Invalid product information.",
    });
  }

  return res.status(500).json({
    success: false,
    message:
      `Unable to ${action} product. Please try again.`,
  });
}

// ============================================
// POST — CREATE NEW PRODUCT
// ============================================

router.post("/", async (req, res) => {
  try {
    // Validate all submitted information.
    const result = validateProductBody(
      req.body
    );

    if (result.error) {
      return res.status(400).json({
        success: false,
        message: result.error,
      });
    }

    // Generate a unique numerical product ID.
    const legacyId =
      await generateProductId();

    // Create the product without stock.
    // New products remain inactive drafts.
    const product = await Product.create({
      legacyId,

      ...result.data,

      stock: 0,
      inventory: [],

      featured: false,
      isActive: false,
    });

    return res.status(201).json({
      success: true,
      message:
        "Product created successfully. It is inactive until published.",
      product,
    });
  } catch (error) {
    return handleDatabaseError(
      res,
      error,
      "create"
    );
  }
});

// ============================================
// GET — PRODUCT DETAILS FOR EDITING
// ============================================

router.get("/:id", async (req, res) => {
  try {
    // Find the product using its legacy ID
    // or its MongoDB document ID.
    const product = await findProduct(
      req.params.id
    );

    if (!product) {
      return res.status(404).json({
        success: false,
        message: "Product not found.",
      });
    }

    // Return full product information,
    // including its current inventory.
    return res.status(200).json({
      success: true,
      product,
    });
  } catch (error) {
    return handleDatabaseError(
      res,
      error,
      "load"
    );
  }
});

// ============================================
// PUT — EDIT EXISTING PRODUCT
// ============================================

router.put("/:id", async (req, res) => {
  try {
    // Validate the full edited product form.
    const result = validateProductBody(
      req.body
    );

    if (result.error) {
      return res.status(400).json({
        success: false,
        message: result.error,
      });
    }

    // Load the existing product first.
    const product = await findProduct(
      req.params.id
    );

    if (!product) {
      return res.status(404).json({
        success: false,
        message: "Product not found.",
      });
    }

    // Check whether the new variation options
    // still support all existing stock records.
    if (
      !inventoryMatchesOptions(
        product.inventory,
        result.data
      )
    ) {
      return res.status(409).json({
        success: false,
        message:
          "These changes conflict with existing inventory. Keep the colours, lengths, densities and lace types used by saved stock records.",
      });
    }

    /**
     * Update only the approved product fields.
     *
     * Crucially, this does NOT update:
     * - inventory
     * - stock
     * - legacyId
     * - isActive
     * - featured
     *
     * The __v condition also helps prevent
     * overwriting a newer inventory or
     * product update.
     */
    const updateResult = await Product.updateOne(
      {
        _id: product._id,
        __v: product.__v,
      },
      {
        $set: result.data,
        $inc: { __v: 1 },
      },
      {
        runValidators: true,
      }
    );

    // Another request may have modified
    // this product after we loaded it.
    if (updateResult.matchedCount === 0) {
      return res.status(409).json({
        success: false,
        message:
          "This product was updated elsewhere. Refresh and try again.",
      });
    }

    // Fetch the latest saved product.
    const updatedProduct =
      await Product.findById(product._id);

    return res.status(200).json({
      success: true,
      message:
        "Product updated successfully.",
      product: updatedProduct,
    });
  } catch (error) {
    return handleDatabaseError(
      res,
      error,
      "update"
    );
  }
});

// ============================================
// PATCH — PUBLISH OR UNPUBLISH PRODUCT
// ============================================

router.patch(
  "/:id/status",
  async (req, res) => {
    try {
      // Only accept one field:
      // { "isActive": true }  -> publish
      // { "isActive": false } -> unpublish
      const body = req.body;

      if (
        !body ||
        typeof body !== "object" ||
        Array.isArray(body) ||
        Object.keys(body).length !== 1 ||
        typeof body.isActive !== "boolean"
      ) {
        return res.status(400).json({
          success: false,
          message:
            "Provide a valid publishing status.",
        });
      }

      // Find the existing product.
      const product = await findProduct(
        req.params.id
      );

      if (!product) {
        return res.status(404).json({
          success: false,
          message: "Product not found.",
        });
      }

      // Only require available stock
      // when publishing, not unpublishing.
      if (
        body.isActive === true &&
        !canPublish(product)
      ) {
        return res.status(409).json({
          success: false,
          message:
            "This product cannot be published yet. Configure valid inventory and make sure at least one unit is in stock.",
        });
      }

      // If the product already has the
      // requested status, no change is needed.
      if (product.isActive === body.isActive) {
        return res.status(200).json({
          success: true,
          message:
            "Product already has this status.",
          product,
        });
      }

      // Update the publishing status without
      // changing product details or inventory.
      const updateResult =
        await Product.updateOne(
          {
            _id: product._id,
            __v: product.__v,
          },
          {
            $set: {
              isActive: body.isActive,
            },
            $inc: { __v: 1 },
          },
          {
            runValidators: true,
          }
        );

      // Prevent a stale publishing request
      // from overwriting newer changes.
      if (updateResult.matchedCount === 0) {
        return res.status(409).json({
          success: false,
          message:
            "This product changed recently. Refresh and try again.",
        });
      }

      // Get the product after updating.
      const updatedProduct =
        await Product.findById(product._id);

      return res.status(200).json({
        success: true,

        message: body.isActive
          ? "Product published successfully."
          : "Product unpublished successfully.",

        product: updatedProduct,
      });
    } catch (error) {
      return handleDatabaseError(
        res,
        error,
        "change status of"
      );
    }
  }
);


 // ============================================
 // DELETE — REMOVE A PRODUCT PERMANENTLY
 // ============================================

router.delete("/:id", async (req, res) => {
  try {
    // Find the product using its MongoDB or legacy ID.
    const product = await findProduct(req.params.id);

    // Return 404 if the product does not exist.
    if (!product) {
      return res.status(404).json({
        success: false,
        message: "Product not found.",
      });
    }

    // Safety: Never delete an active product.
    // Unpublish it first.
    if (product.isActive) {
      return res.status(409).json({
        success: false,
        message: "Unpublish this product before deleting it.",
      });
    }

    
 // ============================================
 // CHECK WHETHER PRODUCT HAS EXISTING ORDERS
 // ============================================

 // Search the orders collection for this product.
 const existingOrder = await Order.exists({
   "items.product": product._id,
 });

 // If an order contains this product, block deletion.
 if (existingOrder) {
   return res.status(409).json({
     success: false,
     message:
       "This product belongs to an existing customer order. Unpublish it instead.",
   });
 }


    // Delete only if the product has not changed
    // since it was loaded.
    const result = await Product.deleteOne({
      _id: product._id,
      __v: product.__v,
      isActive: false,
    });

    // Avoid reporting success if another operation
    // changed or removed the product.
    if (result.deletedCount !== 1) {
      return res.status(409).json({
        success: false,
        message: "Product changed recently. Refresh and try again.",
      });
    }

    // Confirm successful deletion to the frontend.
    return res.status(200).json({
      success: true,
      message: "Product deleted successfully.",
    });
  } catch (error) {
    // Use your existing database error handler.
    return handleDatabaseError(res, error, "delete");
  }
});


