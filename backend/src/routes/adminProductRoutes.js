/**
 * JHAIRS — ADMIN PRODUCT MANAGEMENT
 *
 * POST  /api/admin/products
 *       Create a new inactive product.
 *
 * GET   /api/admin/products/:id
 *       Read complete product details for editing.
 *
 * PUT   /api/admin/products/:id
 *       Update product information safely.
 *
 * PATCH /api/admin/products/:id/status
 *       Publish or unpublish a product.
 *
 * SECURITY:
 * - All routes require administrator authentication.
 * - Product IDs are generated by the backend.
 * - Prices and variations are validated.
 * - Existing inventory is preserved during editing.
 * - Products require available stock before publishing.
 */

