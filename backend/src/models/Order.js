
import mongoose from "mongoose";

// ==========================================
// ORDER ITEM SCHEMA
// ==========================================

// Each order can contain multiple products.
const orderItemSchema = new mongoose.Schema(
  {
    // MongoDB ID of the purchased product.
    product: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Product",
      required: true,
    },

    // Snapshot of the product name at order time.
    name: {
      type: String,
      required: true,
      trim: true,
    },

    // Snapshot of the product image.
    image: {
      type: String,
      default: "",
    },

    // Selected hair colour.
    color: {
      type: String,
      default: "",
    },

    // Selected hair length in inches.
    length: {
      type: Number,
      required: true,
    },

    // Selected wig density, if applicable.
    density: {
      type: String,
      default: "",
    },

    // Selected lace type, if applicable.
    laceType: {
      type: String,
      default: "",
    },

    // Backend-calculated price of one unit.
    unitPrice: {
      type: Number,
      required: true,
      min: 0,
    },

    // Number of units requested.
    quantity: {
      type: Number,
      required: true,
      min: 1,
    },

    // Backend-calculated line subtotal.
    lineTotal: {
      type: Number,
      required: true,
      min: 0,
    },
  },
  {
    // No separate MongoDB ID for each order item.
    _id: false,
  }
);

// ==========================================
// ORDER STATUS HISTORY SCHEMA
// ==========================================

const orderStatusHistorySchema = new mongoose.Schema(
  {
    // Status before the update.
    from: {
      type: String,
      enum: [
        "PENDING",
        "CONFIRMED",
        "PROCESSING",
        "SHIPPED",
        "DELIVERED",
        "CANCELLED",
      ],
      required: true,
    },

    // Status after the update.
    to: {
      type: String,
      enum: [
        "PENDING",
        "CONFIRMED",
        "PROCESSING",
        "SHIPPED",
        "DELIVERED",
        "CANCELLED",
      ],
      required: true,
    },

    // Administrator who performed the action.
    changedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Admin",
      required: true,
    },

    // Time at which the update was recorded.
    changedAt: {
      type: Date,
      required: true,
      default: Date.now,
    },
  },
  {
    _id: false,
  }
);

// ==========================================
// MAIN ORDER SCHEMA
// ==========================================

const orderSchema = new mongoose.Schema(
  {
    // Unique reference generated by the backend.
    orderNumber: {
      type: String,
      required: true,
      unique: true,
      immutable: true,
    },

    // ======================================
    // GUEST CUSTOMER INFORMATION
    // ======================================

    customer: {
      firstName: {
        type: String,
        required: true,
        trim: true,
      },

      lastName: {
        type: String,
        required: true,
        trim: true,
      },

      email: {
        type: String,
        required: true,
        trim: true,
        lowercase: true,
      },

      phone: {
        type: String,
        required: true,
        trim: true,
      },
    },

    // ======================================
    // DELIVERY ADDRESS
    // ======================================

    deliveryAddress: {
      address: {
        type: String,
        required: true,
        trim: true,
      },

      apartment: {
        type: String,
        default: "",
        trim: true,
      },

      city: {
        type: String,
        required: true,
        trim: true,
      },

      state: {
        type: String,
        required: true,
        trim: true,
      },

      country: {
        type: String,
        required: true,
        default: "Nigeria",
        trim: true,
      },
    },

    // Customer's preferred delivery method.
    deliveryMethod: {
      type: String,
      enum: ["standard", "express"],
      default: "standard",
    },

    // Optional customer instructions.
    notes: {
      type: String,
      default: "",
      trim: true,
    },

    // ======================================
    // ORDERED PRODUCTS
    // ======================================

    items: {
      type: [orderItemSchema],

      // Every order must contain at least one item.
      validate: {
        validator: (items) =>
          Array.isArray(items) && items.length > 0,

        message: "An order must contain at least one item.",
      },
    },

    // Sum of all product line totals.
    subtotal: {
      type: Number,
      required: true,
      min: 0,
    },

    // Delivery fee.
    deliveryFee: {
      type: Number,
      default: null,
      min: 0,
    },

    // Final amount after delivery pricing.
    total: {
      type: Number,
      default: null,
      min: 0,
    },

    // ======================================
    // ORDER STATUS
    // ======================================

    orderStatus: {
      type: String,
      enum: [
        "PENDING",
        "CONFIRMED",
        "PROCESSING",
        "SHIPPED",
        "DELIVERED",
        "CANCELLED",
      ],
      default: "PENDING",
    },

    // ======================================
    // ORDER STATUS HISTORY
    // ======================================

    statusHistory: {
      type: [orderStatusHistorySchema],
      default: [],
    },

    // ======================================
    // PAYMENT STATUS
    // ======================================

    paymentStatus: {
      type: String,
      enum: [
        "UNPAID",
        "PENDING",
        "PAID",
        "FAILED",
        "REFUNDED",
      ],
      default: "UNPAID",
    },

    // ======================================
    // PAYMENT TRACKING
    // ======================================

    // Reference from Paystack.
    paymentReference: {
      type: String,
      default: null,
    },

    // Paystack checkout URL.
    paymentAuthorizationUrl: {
      type: String,
      default: null,
    },

    // Records payment problems requiring review.
    paymentIssue: {
      type: String,
      default: null,
    },

    // ======================================
    // PAYMENT INITIALIZATION LOCK
    // ======================================

    // Prevents multiple simultaneous Paystack
    // initialization requests for the same order.
    paymentInitializationStartedAt: {
      type: Date,
      default: null,
    },

    // ======================================
    // INVENTORY DEDUCTION TRACKING
    // ======================================

    inventoryCommitted: {
      type: Boolean,
      default: false,
    },

    // ======================================
    // EMAIL NOTIFICATION TRACKING
    // ======================================

    // Customer payment confirmation email.
    customerConfirmationSentAt: {
      type: Date,
      default: null,
    },

    // Admin new-order notification email.
    adminNotificationSentAt: {
      type: Date,
      default: null,
    },

    // Customer confirmation sending lock.
    customerConfirmationSendingAt: {
      type: Date,
      default: null,
    },

    // Admin notification sending lock.
    adminNotificationSendingAt: {
      type: Date,
      default: null,
    },

    // Customer out-for-delivery email.
    deliveryNotificationSentAt: {
      type: Date,
      default: null,
    },

    // Delivery notification sending lock.
    deliveryNotificationSendingAt: {
      type: Date,
      default: null,
    },

    // ======================================
    // DUPLICATE ORDER PROTECTION
    // ======================================

    orderRequestId: {
      type: String,
      unique: true,
      sparse: true,
      immutable: true,
    },

    // ======================================
    // ORDER REQUEST FINGERPRINT
    // ======================================

    orderRequestHash: {
      type: String,
      default: null,
      immutable: true,
      select: false,
    },
  },
  {
    // Track order creation and update timestamps.
    timestamps: true,
  }
);

// ==========================================
// DATABASE INDEXES
// ==========================================

// Support efficient order searches and sorting.
orderSchema.index({
  createdAt: -1,
  _id: -1,
});

orderSchema.index({
  paymentReference: 1,
});

// ==========================================
// EXPORT ORDER MODEL
// ==========================================

const Order = mongoose.model("Order", orderSchema);

export default Order;
