
import mongoose from "mongoose";

/**
 * JHAIRS — ORDER MODEL
 *
 * Stores guest checkout orders in MongoDB.
 *
 * FEATURES:
 * - Unique order references.
 * - Customer contact information.
 * - Delivery information.
 * - Purchased products and variations.
 * - Backend-calculated prices.
 * - Order and payment statuses.
 * - Payment tracking.
 * - Inventory deduction tracking.
 * - Duplicate-order protection.
 *
 * NEW — STEP 36A:
 * - Order status change history.
 *
 * Customers do not need an account.
 */

// ==========================================
// ORDER ITEM SCHEMA
// ==========================================

// Each order can contain multiple products.
const orderItemSchema = new mongoose.Schema(
  {
    // MongoDB ID of the purchased product.
    product: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Product",
      required: true,
    },

    // Snapshot of the product name at order time.
    name: {
      type: String,
      required: true,
    },

    // Snapshot of the product image.
    image: {
      type: String,
      default: "",
    },

    // Selected hair colour.
    color: {
      type: String,
      default: "",
    },

    // Selected hair length in inches.
    length: {
      type: Number,
      required: true,
    },

    // Selected wig density, if applicable.
    density: {
      type: String,
      default: "",
    },

    // Selected lace type, if applicable.
    laceType: {
      type: String,
      default: "",
    },

    // Backend-calculated price of one unit.
    unitPrice: {
      type: Number,
      required: true,
      min: 0,
    },

    // Number of units requested.
    quantity: {
      type: Number,
      required: true,
      min: 1,
    },

    // Backend-calculated line subtotal.
    lineTotal: {
      type: Number,
      required: true,
      min: 0,
    },
  },
  {
    // No separate MongoDB ID for each order item.
    _id: false,
  }
);

// ==========================================
// NEW — ORDER STATUS HISTORY SCHEMA
// ==========================================

/**
 * Each history entry represents one status change.
 *
 * Example:
 * from: "PENDING"
 * to: "CONFIRMED"
 * changedAt: timestamp
 * changedBy: administrator MongoDB ID
 *
 * These records will be written by our protected
 * backend status-management endpoint.
 */

const orderStatusHistorySchema = new mongoose.Schema(
  {
    // Status before the update.
    from: {
      type: String,
      enum: [
        "PENDING",
        "CONFIRMED",
        "PROCESSING",
        "SHIPPED",
        "DELIVERED",
        "CANCELLED",
      ],
      required: true,
    },

    // Status after the update.
    to: {
      type: String,
      enum: [
        "PENDING",
        "CONFIRMED",
        "PROCESSING",
        "SHIPPED",
        "DELIVERED",
        "CANCELLED",
      ],
      required: true,
    },

    // Administrator who performed the action.
    changedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Admin",
      required: true,
    },

    // Time at which the update was recorded.
    changedAt: {
      type: Date,
      required: true,
      default: Date.now,
    },
  },
  {
    // Each history entry is embedded in its order.
    _id: false,
  }
);

// ==========================================
// MAIN ORDER SCHEMA
// ==========================================

const orderSchema = new mongoose.Schema(
  {
    // Unique reference generated by the backend.
    orderNumber: {
      type: String,
      required: true,
      unique: true,
      immutable: true,
    },

    // ======================================
    // GUEST CUSTOMER INFORMATION
    // ======================================

    customer: {
      firstName: {
        type: String,
        required: true,
        trim: true,
      },

      lastName: {
        type: String,
        required: true,
        trim: true,
      },

      email: {
        type: String,
        required: true,
        trim: true,
        lowercase: true,
      },

      phone: {
        type: String,
        required: true,
        trim: true,
      },
    },

    // ======================================
    // DELIVERY ADDRESS
    // ======================================

    deliveryAddress: {
      address: {
        type: String,
        required: true,
        trim: true,
      },

      apartment: {
        type: String,
        default: "",
        trim: true,
      },

      city: {
        type: String,
        required: true,
        trim: true,
      },

      state: {
        type: String,
        required: true,
        trim: true,
      },

      country: {
        type: String,
        required: true,
        default: "Nigeria",
        trim: true,
      },
    },

    // Customer's preferred delivery method.
    deliveryMethod: {
      type: String,
      enum: ["standard", "express"],
      default: "standard",
    },

    // Optional customer instructions.
    notes: {
      type: String,
      default: "",
      trim: true,
    },

    // ======================================
    // ORDERED PRODUCTS
    // ======================================

    items: {
      type: [orderItemSchema],

      // Every order must contain at least one item.
      validate: {
        validator: (items) =>
          Array.isArray(items) && items.length > 0,

        message:
          "An order must contain at least one item.",
      },
    },

    // Sum of all product line totals.
    subtotal: {
      type: Number,
      required: true,
      min: 0,
    },

    // Delivery has not been priced yet.
    deliveryFee: {
      type: Number,
      default: null,
      min: 0,
    },

    // Final amount is set after delivery pricing.
    total: {
      type: Number,
      default: null,
      min: 0,
    },

    // ======================================
    // ORDER STATUS
    // ======================================

    orderStatus: {
      type: String,
      enum: [
        "PENDING",
        "CONFIRMED",
        "PROCESSING",
        "SHIPPED",
        "DELIVERED",
        "CANCELLED",
      ],
      default: "PENDING",
    },

    // ======================================
    // NEW — ORDER STATUS HISTORY
    // ======================================

    /**
     * Tracks each order status change.
     *
     * New orders begin with an empty history.
     *
     * Existing orders without this field are
     * supported automatically by Mongoose.
     *
     * The future protected admin endpoint will
     * update orderStatus and append history
     * together in one atomic database operation.
     */

    statusHistory: {
      type: [orderStatusHistorySchema],
      default: [],
    },

    // ======================================
    // PAYMENT STATUS
    // ======================================

    /**
     * Payment state remains separate from
     * order fulfilment state.
     *
     * Admin status updates must never
     * automatically mark an order as PAID.
     */

    paymentStatus: {
      type: String,
      enum: [
        "UNPAID",
        "PENDING",
        "PAID",
        "FAILED",
        "REFUNDED",
      ],
      default: "UNPAID",
    },

    // ======================================
    // PAYMENT TRACKING
    // ======================================

    // Reference from the payment provider.
    // Remains null until payment is initialized.
    paymentReference: {
      type: String,
      default: null,
    },

    // ======================================
    // INVENTORY DEDUCTION TRACKING
    // ======================================

    /**
     * Indicates whether product inventory
     * has already been deducted.
     *
     * This field alone does not guarantee
     * protection from duplicate deductions.
     *
     * Payment processing must enforce
     * stock updates atomically.
     */

    inventoryCommitted: {
      type: Boolean,
      default: false,
    },

    // ======================================
    // DUPLICATE ORDER PROTECTION
    // ======================================

    /**
     * Unique order submission identifier.
     *
     * A retry with the same identifier
     * can return the original order.
     *
     * sparse supports older orders without
     * an orderRequestId.
     *
     * immutable prevents changing the ID.
     */

    orderRequestId: {
      type: String,
      unique: true,
      sparse: true,
      immutable: true,
    },

    // ======================================
    // ORDER REQUEST FINGERPRINT
    // ======================================

    /**
     * SHA-256 fingerprint created by
     * the backend during order submission.
     *
     * Used to distinguish:
     *
     * 1. A legitimate retry of the same order.
     * 2. A different order reusing the same ID.
     *
     * Hidden from ordinary database queries.
     *
     * This is not customer authentication.
     */

    orderRequestHash: {
      type: String,
      default: null,
      immutable: true,
      select: false,
    },
  },
  {
    // Track order creation and update timestamps.
    timestamps: true,
  }
);

// ==========================================
// EXPORT ORDER MODEL
// ==========================================

const Order = mongoose.model("Order", orderSchema);

export default Order;
